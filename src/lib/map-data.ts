/** 从节点 location 文本解析出的落点 */
export interface MapPlaceHit {
  place: string;
  geo: [number, number];
}

/**
 * 把 location 文本（如 "范阳、长安、洛阳"）匹配到地名词典坐标。
 * 客户端/服务端通用（不依赖 NodeView）。
 */
export function resolveLocations(loc: string | undefined): MapPlaceHit[] {
  if (!loc) return [];
  const hits: MapPlaceHit[] = [];
  for (const [place, coord] of Object.entries(PLACES)) {
    if (loc.includes(place)) hits.push({ place, geo: coord });
  }
  return hits;
}
